    ANGLE Decart2Polar(int x, int y, int* projectedLength)
    {
        std::int32_t vecX = static_cast<std::int32_t>(x);
        std::int32_t vecY = 0;
        std::int32_t angle = 0;

        if (vecX < 0)
        {
            vecY = neg32Wrap(static_cast<std::int32_t>(y));
            vecX = neg32Wrap(vecX);
            angle = 0x180;
        }
        else
        {
            vecY = static_cast<std::int32_t>(y);
            angle = 0x80;
        }

        for (int i = 0; i < 7; ++i)
        {
            const std::int32_t shiftX = arithmeticShiftRight32(vecX, i);
            const std::int32_t shiftY = arithmeticShiftRight32(vecY, i);
            if (vecY < 0)
            {
                vecY = add32Wrap(vecY, shiftX);
                vecX = sub32Wrap(vecX, shiftY);
                angle = sub32Wrap(angle,
                    kCordicAngleSteps[i]);
            }
            else
            {
                vecY = sub32Wrap(vecY, shiftX);
                vecX = add32Wrap(vecX, shiftY);
                angle = add32Wrap(angle,
                    kCordicAngleSteps[i]);
            }
        }

        if (projectedLength)
        {
            const std::uint32_t product = static_cast<std::uint32_t>(vecX) * 0x0009B74Eu;
            *projectedLength = arithmeticShiftRight32(static_cast<std::int32_t>(product), 20);
        }

        return ANGLE(static_cast<unsigned char>(arithmeticShiftRight32(angle, 1)));
    }


